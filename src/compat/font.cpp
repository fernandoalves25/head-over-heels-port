FONT *font = &g_font;

void textout(BITMAP *bmp, const FONT *f, const char *s, int x, int y, int color) {
    if (!bmp || !s) return;
    if (!f) f = &g_font;
    if (color < 0) color = 0xFFFF;  // -1 no Allegro = cores da propria fonte; aqui, branco
    for (; *s; s++, x += f->cell_w) {
        const char *rows = glyph_for(*s);
        if (!rows || std::strlen(rows) != 35) continue;
        for (int r = 0; r < 7; r++)
            for (int col = 0; col < 5; col++)
                if (rows[r * 5 + col] == '#') putpixel(bmp, x + 1 + col, y + r, color);
    }
}

void textprintf(BITMAP *bmp, const FONT *f, int x, int y, int color, const char *fmt, ...) {
    char buf[512];
    va_list ap;
    va_start(ap, fmt);
    std::vsnprintf(buf, sizeof buf, fmt, ap);
    va_end(ap);
    textout(bmp, f, buf, x, y, color);
}

int text_length(const FONT *f, const char *s) {
    return static_cast<int>(std::strlen(s)) * (f ? f->cell_w : g_font.cell_w);
}

int text_height(const FONT *f) { return f ? f->cell_h : g_font.cell_h; }
